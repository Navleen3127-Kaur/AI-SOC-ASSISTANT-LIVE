"""Incident report rendering in Markdown and PDF formats."""

from pathlib import Path
from jinja2 import Environment, FileSystemLoader, select_autoescape
from fpdf import FPDF

from soc_analyst.models.schemas import IncidentReport

TEMPLATE_DIR = Path(__file__).resolve().parent.parent / "templates"


def render_incident_report(report: IncidentReport) -> str:
    env = Environment(
        loader=FileSystemLoader(str(TEMPLATE_DIR)),
        autoescape=select_autoescape(default=False),
    )
    template = env.get_template("incident_report.md.j2")
    return template.render(report=report)


class FPDFReport(FPDF):
    """Custom FPDF class to add professional headers and footers."""
    
    def header(self):
        if self.page_no() == 1:
            return
        # Header banner style
        self.set_fill_color(10, 15, 29)  # #0a0f1d (dark theme color)
        self.rect(0, 0, 210, 25, "F")
        self.set_text_color(6, 182, 212)  # #06b6d4 (accent cyan)
        self.set_font("helvetica", "B", 14)
        self.set_y(8)
        self.cell(0, 10, "AI SOC ANALYST - INCIDENT RESPONSE REPORT", align="C")
        self.ln(20)

    def footer(self):
        if self.page_no() == 1:
            return
        self.set_y(-15)
        self.set_font("helvetica", "I", 8)
        self.set_text_color(156, 163, 175)  # #9ca3af (text muted)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}} - Security Operations Confidential", align="C")


def render_pdf_report(report: IncidentReport) -> bytes:
    """Generates a structured PDF document from an IncidentReport using fpdf2."""
    pdf = FPDFReport()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.alias_nb_pages()
    
    # -------------------------------------------------------------
    # Page 1: Dark-Themed Professional Title Page
    # -------------------------------------------------------------
    pdf.add_page()
    pdf.set_fill_color(10, 15, 29)  # #0a0f1d
    pdf.rect(0, 0, 210, 297, "F")
    
    # Title Text
    pdf.set_y(80)
    pdf.set_font("helvetica", "B", 24)
    pdf.set_text_color(6, 182, 212)  # Cyan
    pdf.cell(0, 12, "AI SECURITY OPERATIONS CENTER", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 12, "INCIDENT INVESTIGATION REPORT", align="C", new_x="LMARGIN", new_y="NEXT")
    
    pdf.ln(10)
    pdf.set_font("helvetica", "B", 14)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(0, 10, f"Target: {report.title}", align="C", new_x="LMARGIN", new_y="NEXT")
    
    pdf.ln(25)
    # Severity Badge on Cover Page
    pdf.set_font("helvetica", "B", 12)
    sev_color_cover = (239, 68, 68) if report.overall_severity.value.lower() in ["critical", "high"] else (245, 158, 11)
    pdf.set_text_color(sev_color_cover[0], sev_color_cover[1], sev_color_cover[2])
    pdf.cell(0, 10, f"SEVERITY LEVEL: {report.overall_severity.value.upper()}", align="C", new_x="LMARGIN", new_y="NEXT")
    
    # Title Page Metadata Block
    pdf.set_y(190)
    pdf.set_font("helvetica", "", 9.5)
    pdf.set_text_color(156, 163, 175)
    pdf.cell(0, 6, f"Incident ID: {report.incident_id}", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, f"Report Version: {report.report_version}", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, f"Execution Mode: {report.execution_mode}", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, f"LLM Model: {report.llm_model} ({report.llm_provider})", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, f"Generation Time: {report.generated_at.strftime('%Y-%m-%d %H:%M:%S UTC')}", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)
    pdf.set_font("helvetica", "B", 9)
    pdf.cell(0, 6, "CONFIDENTIAL - SECURITY OPERATIONS PERSONNEL ONLY", align="C", new_x="LMARGIN", new_y="NEXT")

    # -------------------------------------------------------------
    # Page 2+: Detailed Report Content
    # -------------------------------------------------------------
    pdf.add_page()
    pdf.set_y(32)
    
    # 1. Report Metadata Table Block
    pdf.set_font("helvetica", "B", 11)
    pdf.set_text_color(6, 182, 212)
    pdf.cell(0, 7, "Report Information & Metadata", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)
    pdf.set_font("helvetica", "", 9.5)
    pdf.set_text_color(55, 65, 81)
    
    def draw_row(k1, v1, k2, v2):
        pdf.cell(45, 6, f"  {k1}:", border=1)
        pdf.cell(50, 6, f" {v1}", border=1)
        pdf.cell(45, 6, f"  {k2}:", border=1)
        pdf.cell(50, 6, f" {v2}", border=1, new_x="LMARGIN", new_y="NEXT")
        
    draw_row("Report Version", report.report_version, "Generated By", report.generated_by)
    draw_row("LLM Provider", report.llm_provider, "LLM Model", report.llm_model)
    draw_row("Execution Mode", report.execution_mode, "Report Type", report.report_type)
    pdf.ln(4)
    
    # 2. Executive Report Metrics Box
    pdf.set_font("helvetica", "B", 11)
    pdf.set_text_color(6, 182, 212)
    pdf.cell(0, 7, "Executive Metrics Summary", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)
    pdf.set_font("helvetica", "", 9.5)
    pdf.set_text_color(55, 65, 81)
    
    draw_row("Alerts Analyzed", str(report.total_alerts_analyzed), "Correlated Alerts", str(report.correlated_alerts_count))
    draw_row("Affected Hosts", str(report.affected_hosts_count), "Affected Users", str(report.affected_users_count))
    draw_row("Critical Assets", str(report.critical_assets_count), "FP Probability", report.false_positive_probability)
    draw_row("Threat Intel Hits", str(report.threat_intel_hits), "MITRE Techniques", str(report.mitre_techniques_count))
    pdf.ln(4)

    # 3. Kill Chain Attack Progression Flowchart (ASCII/Shapes)
    if report.attack_progression:
        pdf.set_font("helvetica", "B", 11)
        pdf.set_text_color(6, 182, 212)
        pdf.cell(0, 7, "Cyber Kill Chain - Attack Progression", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1)
        
        for i, step in enumerate(report.attack_progression):
            # Print steps with visual colors
            pdf.set_font("helvetica", "B", 9.5)
            pdf.set_text_color(220, 38, 38)
            pdf.cell(0, 6, f"  Step {i+1}: {step}", new_x="LMARGIN", new_y="NEXT")
            if i < len(report.attack_progression) - 1:
                pdf.set_font("helvetica", "", 9)
                pdf.set_text_color(107, 114, 128)
                pdf.cell(0, 5, "         |", new_x="LMARGIN", new_y="NEXT")
                pdf.cell(0, 5, "         v", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)
        
    def add_section(title: str, content: str | list[str]):
        # Check if page space is low, trigger page break if needed
        if pdf.get_y() > 240:
            pdf.add_page()
            pdf.set_y(30)
            
        pdf.set_font("helvetica", "B", 11)
        pdf.set_text_color(6, 182, 212)  # Cyan
        pdf.cell(0, 7, title, new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1)  # prevent merging with headings
        pdf.set_font("helvetica", size=9.5)
        pdf.set_text_color(55, 65, 81)  # Gray-700
        
        def clean_txt(t: str) -> str:
            # Standardize unicode characters for standard FPDF winansi encoding
            return str(t).replace("•", "-").replace("✓", "[PASS]").encode("latin-1", errors="replace").decode("latin-1")
        
        if isinstance(content, list):
            if not content:
                pdf.cell(0, 5, "None recorded.", new_x="LMARGIN", new_y="NEXT")
            else:
                for item in content:
                    pdf.multi_cell(0, 5.5, clean_txt(item), new_x="LMARGIN", new_y="NEXT")
        else:
            if not content:
                pdf.cell(0, 5, "None recorded.", new_x="LMARGIN", new_y="NEXT")
            else:
                pdf.multi_cell(0, 5.5, clean_txt(content), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)
        
    add_section("1. Executive Summary", report.executive_summary)
    add_section("2. Incident Overview", report.incident_overview)
    add_section("3. Timeline", report.timeline)
    add_section("4. Affected Assets", report.affected_assets)
    add_section("5. Affected Users", report.affected_users)
    add_section("6. Indicators of Compromise (IOCs)", report.indicators_of_compromise)
    add_section("7. Threat Intelligence Summary", report.threat_intel_summary.split("\n") if report.threat_intel_summary else [])
    
    mitre_lines = []
    if report.mitre_tactics_observed:
        mitre_lines.append(f"Tactics: {', '.join(report.mitre_tactics_observed)}")
    if report.mitre_techniques_observed:
        mitre_lines.append(f"Techniques: {', '.join(report.mitre_techniques_observed)}")
    add_section("8. MITRE ATT&CK Mapping", mitre_lines)
    
    # Severity & Risk Score Breakdown
    risk_lines = [
        f"Overall Severity: {report.overall_severity.value.upper()}",
        f"Final Risk Score: {report.risk_score}/100.0",
        "Risk Score Breakdown:"
    ]
    for k, v in report.risk_breakdown.items():
        risk_lines.append(f"  - {k}: {v}")
    add_section("9. Severity & Risk Score Breakdown", risk_lines)
    
    # AI Decision Reasoning
    reason_lines = [f"  {r}" for r in report.ai_decision_reasoning]
    add_section("10. AI Decision Reasoning", reason_lines)
    
    # Incident Confidence Summary
    conf_lines = [
        f"Confidence Score: {report.confidence_score}%",
        f"Confidence Level: {report.confidence_level}",
        "Confidence Breakdown:"
    ]
    for k, v in report.confidence_breakdown.items():
        conf_lines.append(f"  - {k}: {v}%")
    add_section("11. Incident Confidence Summary", conf_lines)
    
    # Incident Correlation Details
    corr_lines = [
        f"Correlation Score: {report.correlation_score}%",
        "Correlation Reasons:"
    ]
    for r in report.correlation_breakdown:
        corr_lines.append(f"  {r}")
    add_section("12. Incident Correlation Details", corr_lines)
    
    add_section("13. Threat Explanation", report.threat_explanation)
    add_section("14. Investigation Findings", report.investigation_findings)
    add_section("15. Containment Actions", report.containment_actions)
    add_section("16. Eradication", report.eradication_actions)
    add_section("17. Recovery", report.recovery_actions)
    add_section("18. Lessons Learned", report.lessons_learned)
    add_section("19. Executive Recommendations", report.executive_recommendations)
    add_section("20. Analyst Conclusion", report.analyst_conclusion)
    
    return bytes(pdf.output())
